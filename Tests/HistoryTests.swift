var history = ClipboardHistory()
assert(history.count == 0)
for index in 0..<1_005 { history.record("Copy \(index)") }
assert(history.count == 1_000, "History must stay capped")
assert(history[0] == "Copy 1004", "Newest copy should be first")
assert(history[999] == "Copy 5", "Oldest excess records must be evicted")
let otherRun = ClipboardHistory()
assert(otherRun.count == 0, "New sessions must start empty")
history.removeAll()
assert(history.count == 0)
history.record("Hello 👋\nSecond line")
assert(history[0] == "Hello 👋\nSecond line", "Unicode and line breaks must survive")
history.record("Hello 👋\nSecond line ")
history.record("Hello 👋\nSecond line")
history.record("Another copy")
history.removeMatches(for: "Unrecorded edit")
assert(history.count == 4, "Clearing unrecorded text must preserve history")
history.removeMatches(for: "Hello 👋\nSecond line")
assert(history.count == 2, "Clear must remove all exact matches")
assert(history[0] == "Another copy" && history[1] == "Hello 👋\nSecond line ",
       "Clear must preserve the order and whitespace of other entries")
print("History tests passed: cap, ordering, eviction, fresh session, clear, Unicode, exact matches.")
